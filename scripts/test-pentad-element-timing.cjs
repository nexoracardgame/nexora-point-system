const fs=require('node:fs'),assert=require('node:assert/strict');
const fixture=fs.readFileSync('scripts/test-pentad.cjs','utf8');
const {store,rules,triad,presentation}=new Function('require',fixture.slice(0,fixture.indexOf('const first='))+'return {store,rules,triad,presentation:load("lib/pentad-element-presentation.ts")};')(require);
let now=Date.now();
const host={id:'element-host',name:'HOST',image:''},rival={id:'element-rival',name:'RIVAL',image:''};
const room=store.newPentadRoom('element-timing',host,now);
const act=(actor,action,extra={})=>store.applyPentadAction(room,actor,{action,epoch:room.epoch,...extra},now);
act(rival,'join');act(host,'start');
const water=triad.triadCards.find(card=>card.kind==='monster'&&card.element==='water').cardNo;
const fire=triad.triadCards.find(card=>card.kind==='monster'&&card.element==='fire').cardNo;
act(host,'ready',{deck:rules.completePentadDeck({monsters:[water],hand:[],reserve:[]})});
act(rival,'ready',{deck:rules.completePentadDeck({monsters:[fire],hand:[],reserve:[]})});
store.tickPentadRoom(room,now);act(host,'pick',{cardNo:water});act(rival,'pick',{cardNo:fire});store.tickPentadRoom(room,now);
assert.equal(room.phase,'result');const round=room.rounds.at(-1);
assert.equal(round.winner,'host');assert.equal(room.score.host,1);
assert.equal(presentation.PENTAD_ELEMENT_HOLD_MS,6000);
assert.equal(round.endsAt-now,presentation.PENTAD_ELEMENT_SCENE_MS+2000);
assert.equal(presentation.hasPentadElementClash(round),true);
for(const turn of [2,3,4,5])assert.equal(presentation.hasPentadElementClash({...round,turn}),false);
assert.equal(presentation.hasPentadElementClash({...round,finalDuel:true}),false);
assert.equal(presentation.hasPentadElementClash({...round,mains:{host:'__pass__',challenger:fire}}),false);
now+=presentation.PENTAD_ELEMENT_SCENE_MS;store.tickPentadRoom(room,now);assert.equal(room.phase,'result','Server retains transport buffer after the full reveal + hold');
act(host,'complete',{roundId:round.id});store.tickPentadRoom(room,now);assert.equal(room.phase,'result','One client cannot cut the other player off');
act(rival,'complete',{roundId:round.id});store.tickPentadRoom(room,now);assert.equal(room.phase,'select');assert.equal(room.turn,2);
assert.equal(room.score.host,1,'Presentation timing never awards duplicate points');
console.log('Element timing: 1.8s reveal + 6s result hold, server buffer, both-player completion, correct score, missing-main/final-duel/later-turn gates passed');
